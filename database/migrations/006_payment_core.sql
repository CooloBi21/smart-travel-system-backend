-- ------------------------------------------------------------
-- 1. Payments
--
-- One booking may have multiple payment attempts.
-- Only one successful payment is allowed for each booking.
-- ------------------------------------------------------------

CREATE TABLE public.payments (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id              INTEGER NOT NULL,

    amount                  NUMERIC(14,2) NOT NULL,
    currency                VARCHAR(3) NOT NULL DEFAULT 'VND',

    payment_method          VARCHAR(30) NOT NULL DEFAULT 'SIMULATED',

    status                  VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    transaction_reference   VARCHAR(100),

    paid_at                 TIMESTAMPTZ,

    failure_reason          VARCHAR(500),

    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_payments_bookings
        FOREIGN KEY (booking_id)
        REFERENCES public.bookings(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_payments_amount
        CHECK (
            amount >= 0
        ),

    CONSTRAINT ck_payments_currency
        CHECK (
            currency = 'VND'
        ),

    CONSTRAINT ck_payments_method
        CHECK (
            payment_method IN (
                'SIMULATED'
            )
        ),

    CONSTRAINT ck_payments_status
        CHECK (
            status IN (
                'PENDING',
                'SUCCESS',
                'FAILED',
                'CANCELLED'
            )
        ),

    CONSTRAINT ck_payments_transaction_reference
        CHECK (
            transaction_reference IS NULL
            OR BTRIM(transaction_reference) <> ''
        ),

    CONSTRAINT ck_payments_lifecycle
        CHECK (
            (
                status = 'PENDING'
                AND paid_at IS NULL
            )
            OR
            (
                status = 'SUCCESS'
                AND paid_at IS NOT NULL
                AND transaction_reference IS NOT NULL
            )
            OR
            (
                status = 'FAILED'
                AND paid_at IS NULL
            )
            OR
            (
                status = 'CANCELLED'
                AND paid_at IS NULL
            )
        )
);


-- ------------------------------------------------------------
-- 2. Indexes
-- ------------------------------------------------------------

CREATE INDEX idx_payments_booking_created_at
ON public.payments (
    booking_id,
    created_at DESC
);


CREATE INDEX idx_payments_status_created_at
ON public.payments (
    status,
    created_at DESC
);


CREATE UNIQUE INDEX uq_payments_transaction_reference
ON public.payments (
    transaction_reference
)
WHERE transaction_reference IS NOT NULL;


-- ------------------------------------------------------------
-- 3. Only one successful payment per booking
-- ------------------------------------------------------------

CREATE UNIQUE INDEX uq_payments_one_success_per_booking
ON public.payments (
    booking_id
)
WHERE status = 'SUCCESS';


-- ------------------------------------------------------------
-- 4. Updated timestamp
-- ------------------------------------------------------------

CREATE TRIGGER trg_payments_updated_at
BEFORE UPDATE ON public.payments
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 5. Documentation
-- ------------------------------------------------------------

COMMENT ON TABLE public.payments IS
'Payment attempts associated with customer bookings. A booking may have multiple attempts, but only one successful payment is allowed.';


COMMENT ON COLUMN public.payments.amount IS
'Payment amount captured from the booking total at payment creation time.';


COMMENT ON COLUMN public.payments.transaction_reference IS
'Unique reference representing a payment transaction or simulated payment attempt.';


COMMENT ON COLUMN public.payments.status IS
'Payment lifecycle: PENDING, SUCCESS, FAILED, CANCELLED.';


COMMENT ON INDEX public.uq_payments_one_success_per_booking IS
'Ensures that each booking can have at most one successful payment.';
