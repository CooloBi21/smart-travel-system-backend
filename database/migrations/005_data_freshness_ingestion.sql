-- ------------------------------------------------------------
-- 1. External sources
--
-- Defines approved external data sources and their freshness
-- expectations. Credentials are NOT stored in this table.
-- ------------------------------------------------------------

CREATE TABLE public.external_sources (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code                    VARCHAR(80) NOT NULL,
    name                    VARCHAR(180) NOT NULL,

    source_type             VARCHAR(30) NOT NULL,
    base_url                TEXT NOT NULL,

    is_active               BOOLEAN NOT NULL DEFAULT TRUE,

    crawl_interval_minutes  INTEGER NOT NULL DEFAULT 1440,
    max_staleness_minutes   INTEGER NOT NULL DEFAULT 4320,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_external_sources_code
        UNIQUE (code),

    CONSTRAINT ck_external_sources_code_format
        CHECK (
            code ~ '^[A-Z][A-Z0-9_]*$'
        ),

    CONSTRAINT ck_external_sources_name
        CHECK (
            BTRIM(name) <> ''
        ),

    CONSTRAINT ck_external_sources_base_url
        CHECK (
            BTRIM(base_url) <> ''
        ),

    CONSTRAINT ck_external_sources_type
        CHECK (
            source_type IN (
                'OFFICIAL_WEBSITE',
                'PUBLIC_API',
                'RSS',
                'PARTNER',
                'OPEN_DATA'
            )
        ),

    CONSTRAINT ck_external_sources_crawl_interval
        CHECK (
            crawl_interval_minutes > 0
        ),

    CONSTRAINT ck_external_sources_max_staleness
        CHECK (
            max_staleness_minutes >= crawl_interval_minutes
        )
);


CREATE INDEX idx_external_sources_active_type
ON public.external_sources (
    is_active,
    source_type
);


CREATE TRIGGER trg_external_sources_updated_at
BEFORE UPDATE ON public.external_sources
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 2. Ingestion runs
--
-- One row represents one crawler / ingestion execution.
-- ------------------------------------------------------------

CREATE TABLE public.ingestion_runs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_id           INTEGER NOT NULL,

    started_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    finished_at         TIMESTAMPTZ,

    status              VARCHAR(20) NOT NULL DEFAULT 'RUNNING',

    items_fetched       INTEGER NOT NULL DEFAULT 0,
    items_created       INTEGER NOT NULL DEFAULT 0,
    items_updated       INTEGER NOT NULL DEFAULT 0,
    items_unchanged     INTEGER NOT NULL DEFAULT 0,
    items_failed        INTEGER NOT NULL DEFAULT 0,

    error_summary       TEXT,

    CONSTRAINT fk_ingestion_runs_sources
        FOREIGN KEY (source_id)
        REFERENCES public.external_sources(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_ingestion_runs_status
        CHECK (
            status IN (
                'RUNNING',
                'SUCCESS',
                'PARTIAL',
                'FAILED'
            )
        ),

    CONSTRAINT ck_ingestion_runs_lifecycle
        CHECK (
            (
                status = 'RUNNING'
                AND finished_at IS NULL
            )
            OR
            (
                status IN (
                    'SUCCESS',
                    'PARTIAL',
                    'FAILED'
                )
                AND finished_at IS NOT NULL
                AND finished_at >= started_at
            )
        ),

    CONSTRAINT ck_ingestion_runs_counts
        CHECK (
            items_fetched >= 0
            AND items_created >= 0
            AND items_updated >= 0
            AND items_unchanged >= 0
            AND items_failed >= 0
            AND (
                items_created
                + items_updated
                + items_unchanged
                + items_failed
            ) <= items_fetched
        )
);


CREATE INDEX idx_ingestion_runs_source_started
ON public.ingestion_runs (
    source_id,
    started_at DESC
);


CREATE INDEX idx_ingestion_runs_status_started
ON public.ingestion_runs (
    status,
    started_at DESC
);


-- ------------------------------------------------------------
-- 3. External items
--
-- Latest known snapshot of one item from an external source.
-- Raw and normalized payloads are separated.
-- ------------------------------------------------------------

CREATE TABLE public.external_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    source_id               INTEGER NOT NULL,
    last_ingestion_run_id   BIGINT NOT NULL,

    external_key            VARCHAR(500),
    source_url              TEXT NOT NULL,

    content_type            VARCHAR(30) NOT NULL,

    raw_payload             JSONB NOT NULL,
    normalized_payload      JSONB,

    content_hash            VARCHAR(64) NOT NULL,

    source_published_at     TIMESTAMPTZ,

    first_seen_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fetched_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    processing_status       VARCHAR(20) NOT NULL DEFAULT 'FETCHED',

    CONSTRAINT fk_external_items_sources
        FOREIGN KEY (source_id)
        REFERENCES public.external_sources(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_external_items_last_run
        FOREIGN KEY (last_ingestion_run_id)
        REFERENCES public.ingestion_runs(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_external_items_source_url
        UNIQUE (
            source_id,
            source_url
        ),

    CONSTRAINT ck_external_items_source_url
        CHECK (
            BTRIM(source_url) <> ''
        ),

    CONSTRAINT ck_external_items_content_type
        CHECK (
            content_type IN (
                'DESTINATION',
                'NEWS',
                'EVENT',
                'TRAVEL_INFO'
            )
        ),

    CONSTRAINT ck_external_items_raw_payload
        CHECK (
            jsonb_typeof(raw_payload) = 'object'
        ),

    CONSTRAINT ck_external_items_normalized_payload
        CHECK (
            normalized_payload IS NULL
            OR jsonb_typeof(normalized_payload) = 'object'
        ),

    CONSTRAINT ck_external_items_content_hash
        CHECK (
            content_hash ~ '^[0-9a-f]{64}$'
        ),

    CONSTRAINT ck_external_items_processing_status
        CHECK (
            processing_status IN (
                'FETCHED',
                'NORMALIZED',
                'APPLIED',
                'REJECTED',
                'ERROR'
            )
        ),

    CONSTRAINT ck_external_items_seen_times
        CHECK (
            last_seen_at >= first_seen_at
        )
);


CREATE UNIQUE INDEX uq_external_items_external_key
ON public.external_items (
    source_id,
    external_key
)
WHERE external_key IS NOT NULL;


CREATE INDEX idx_external_items_source_last_seen
ON public.external_items (
    source_id,
    last_seen_at DESC
);


CREATE INDEX idx_external_items_processing_status
ON public.external_items (
    processing_status,
    fetched_at DESC
);


CREATE INDEX idx_external_items_content_hash
ON public.external_items (content_hash);


CREATE INDEX idx_external_items_last_ingestion_run
ON public.external_items (last_ingestion_run_id);


-- ------------------------------------------------------------
-- 4. Destination provenance
--
-- Connects canonical STS destinations to external evidence.
-- source_id and source_url are intentionally NOT duplicated:
-- both are available through external_item_id.
-- ------------------------------------------------------------

CREATE TABLE public.destination_sources (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    destination_id      INTEGER NOT NULL,
    external_item_id    BIGINT NOT NULL,

    is_primary          BOOLEAN NOT NULL DEFAULT FALSE,

    first_seen_at       TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_verified_at    TIMESTAMPTZ,

    CONSTRAINT fk_destination_sources_destinations
        FOREIGN KEY (destination_id)
        REFERENCES public.destinations(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_destination_sources_external_items
        FOREIGN KEY (external_item_id)
        REFERENCES public.external_items(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_destination_sources_mapping
        UNIQUE (
            destination_id,
            external_item_id
        ),

    CONSTRAINT ck_destination_sources_seen_times
        CHECK (
            last_seen_at >= first_seen_at
        ),

    CONSTRAINT ck_destination_sources_verified_time
        CHECK (
            last_verified_at IS NULL
            OR last_verified_at >= first_seen_at
        )
);


CREATE INDEX idx_destination_sources_destination
ON public.destination_sources (destination_id);


CREATE INDEX idx_destination_sources_external_item
ON public.destination_sources (external_item_id);


CREATE INDEX idx_destination_sources_verified
ON public.destination_sources (last_verified_at);


CREATE UNIQUE INDEX uq_destination_sources_one_primary
ON public.destination_sources (destination_id)
WHERE is_primary = TRUE;


-- ------------------------------------------------------------
-- 5. Derived destination freshness
--
-- Freshness is calculated, NOT stored.
-- ------------------------------------------------------------

CREATE VIEW public.destination_source_freshness AS

SELECT
    ds.destination_id,
    ds.external_item_id,

    es.id AS source_id,
    es.code AS source_code,
    es.name AS source_name,
    es.source_type,

    ei.source_url,
    ei.content_hash,

    ds.is_primary,
    ds.last_seen_at,
    ds.last_verified_at,

    es.max_staleness_minutes,

    CASE
        WHEN ds.last_verified_at IS NULL
            THEN NULL
        ELSE ROUND(
            EXTRACT(
                EPOCH FROM (
                    NOW() - ds.last_verified_at
                )
            ) / 60.0,
            2
        )
    END AS minutes_since_verification,

    CASE
        WHEN ds.last_verified_at IS NULL
            THEN TRUE
        WHEN NOW() >
            ds.last_verified_at
            + (
                es.max_staleness_minutes
                * INTERVAL '1 minute'
            )
            THEN TRUE
        ELSE FALSE
    END AS is_stale

FROM public.destination_sources ds

JOIN public.external_items ei
    ON ei.id = ds.external_item_id

JOIN public.external_sources es
    ON es.id = ei.source_id;


