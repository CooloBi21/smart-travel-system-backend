COMMENT ON TABLE public.external_sources IS
'Approved external data sources and configurable crawling/freshness policies.';

COMMENT ON TABLE public.ingestion_runs IS
'Execution history for external data ingestion jobs.';

COMMENT ON TABLE public.external_items IS
'Latest known external-source item snapshot including raw payload, normalized payload and content hash.';

COMMENT ON TABLE public.destination_sources IS
'Provenance links between canonical destinations and external-source evidence.';

COMMENT ON VIEW public.destination_source_freshness IS
'Derived destination provenance freshness. Freshness status is calculated from last_verified_at and source max_staleness_minutes.';

COMMENT ON COLUMN public.external_items.content_hash IS
'SHA-256 lowercase hexadecimal content fingerprint used to detect external content changes.';

COMMENT ON COLUMN public.destination_sources.last_verified_at IS
'Time when this external evidence was last successfully verified for the canonical destination.';