-- ------------------------------------------------------------
-- 1. Shared updated_at trigger function
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION public.update_timestamp()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$;


-- ------------------------------------------------------------
-- 2. Roles
-- ------------------------------------------------------------

CREATE TABLE public.roles (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code        VARCHAR(50) NOT NULL,
    name        VARCHAR(100) NOT NULL,
    description TEXT,

    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_roles_code
        UNIQUE (code),

    CONSTRAINT ck_roles_code_format
        CHECK (code ~ '^[A-Z][A-Z0-9_]*$')
);


CREATE TRIGGER trg_roles_updated_at
BEFORE UPDATE ON public.roles
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 3. Users
-- ------------------------------------------------------------

CREATE TABLE public.users (
    id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    role_id       INTEGER NOT NULL,

    email         VARCHAR(255) NOT NULL,
    password_hash TEXT NOT NULL,

    full_name     VARCHAR(150) NOT NULL,
    phone         VARCHAR(30),
    avatar_url    TEXT,

    is_active     BOOLEAN NOT NULL DEFAULT TRUE,

    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_users_roles
        FOREIGN KEY (role_id)
        REFERENCES public.roles(id)
        ON DELETE RESTRICT
);


CREATE UNIQUE INDEX uq_users_email_ci
ON public.users (LOWER(email));


CREATE INDEX idx_users_role_id
ON public.users (role_id);


CREATE TRIGGER trg_users_updated_at
BEFORE UPDATE ON public.users
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 4. Companies
-- ------------------------------------------------------------

CREATE TABLE public.companies (
    id                INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    account_user_id   INTEGER NOT NULL,

    name              VARCHAR(255) NOT NULL,
    slug              VARCHAR(180) NOT NULL,

    description       TEXT,
    logo_url          TEXT,

    contact_email     VARCHAR(255),
    contact_phone     VARCHAR(30),

    status            VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    created_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_companies_account_user
        FOREIGN KEY (account_user_id)
        REFERENCES public.users(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_companies_account_user
        UNIQUE (account_user_id),

    CONSTRAINT uq_companies_slug
        UNIQUE (slug),

    CONSTRAINT ck_companies_slug_format
        CHECK (
            slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
        ),

    CONSTRAINT ck_companies_status
        CHECK (
            status IN (
                'PENDING',
                'ACTIVE',
                'SUSPENDED',
                'ARCHIVED'
            )
        )
);


CREATE INDEX idx_companies_status
ON public.companies (status);


CREATE TRIGGER trg_companies_updated_at
BEFORE UPDATE ON public.companies
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


