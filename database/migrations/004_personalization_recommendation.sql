-- ------------------------------------------------------------
-- 1. User preferences
-- One preference profile per customer account.
-- ------------------------------------------------------------

CREATE TABLE public.user_preferences (
    id                          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id                     INTEGER NOT NULL,

    preferred_category_id       INTEGER,
    preferred_destination_id    INTEGER,

    budget_min                  NUMERIC(14,2) NOT NULL DEFAULT 0,
    budget_max                  NUMERIC(14,2),

    preferred_duration_days     INTEGER,
    travel_style                VARCHAR(30),
    travel_with                 VARCHAR(30),

    created_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at                  TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_user_preferences_users
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_user_preferences_categories
        FOREIGN KEY (preferred_category_id)
        REFERENCES public.tour_categories(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_user_preferences_destinations
        FOREIGN KEY (preferred_destination_id)
        REFERENCES public.destinations(id)
        ON DELETE SET NULL,

    CONSTRAINT uq_user_preferences_user
        UNIQUE (user_id),

    CONSTRAINT ck_user_preferences_budget_min
        CHECK (
            budget_min >= 0
        ),

    CONSTRAINT ck_user_preferences_budget_range
        CHECK (
            budget_max IS NULL
            OR budget_max >= budget_min
        ),

    CONSTRAINT ck_user_preferences_duration
        CHECK (
            preferred_duration_days IS NULL
            OR preferred_duration_days > 0
        ),

    CONSTRAINT ck_user_preferences_travel_style
        CHECK (
            travel_style IS NULL
            OR travel_style IN (
                'BEACH',
                'CULTURE',
                'EXPLORE',
                'RELAX',
                'ADVENTURE'
            )
        ),

    CONSTRAINT ck_user_preferences_travel_with
        CHECK (
            travel_with IS NULL
            OR travel_with IN (
                'SOLO',
                'COUPLE',
                'FAMILY',
                'FRIENDS',
                'GROUP'
            )
        )
);


CREATE INDEX idx_user_preferences_category
ON public.user_preferences (preferred_category_id);


CREATE INDEX idx_user_preferences_destination
ON public.user_preferences (preferred_destination_id);


CREATE TRIGGER trg_user_preferences_updated_at
BEFORE UPDATE ON public.user_preferences
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 2. Favorites
-- ------------------------------------------------------------

CREATE TABLE public.favorites (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id         INTEGER NOT NULL,
    tour_id         INTEGER NOT NULL,

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_favorites_users
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_favorites_tours
        FOREIGN KEY (tour_id)
        REFERENCES public.tours(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_favorites_user_tour
        UNIQUE (
            user_id,
            tour_id
        )
);


CREATE INDEX idx_favorites_tour_id
ON public.favorites (tour_id);


-- ------------------------------------------------------------
-- 3. Behavior logs
--
-- Append-only user interaction events used by recommendation.
-- ------------------------------------------------------------

CREATE TABLE public.behavior_logs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id             INTEGER,
    tour_id             INTEGER,

    action_type         VARCHAR(30) NOT NULL,

    duration_seconds    INTEGER,
    metadata            JSONB NOT NULL DEFAULT '{}'::jsonb,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_behavior_logs_users
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON DELETE SET NULL,

    CONSTRAINT fk_behavior_logs_tours
        FOREIGN KEY (tour_id)
        REFERENCES public.tours(id)
        ON DELETE SET NULL,

    CONSTRAINT ck_behavior_logs_action_type
        CHECK (
            action_type IN (
                'VIEW',
                'SEARCH',
                'FAVORITE',
                'UNFAVORITE',
                'BOOKING_INTENT',
                'BOOKING'
            )
        ),

    CONSTRAINT ck_behavior_logs_duration
        CHECK (
            duration_seconds IS NULL
            OR duration_seconds >= 0
        ),

    CONSTRAINT ck_behavior_logs_metadata_object
        CHECK (
            jsonb_typeof(metadata) = 'object'
        )
);


CREATE INDEX idx_behavior_logs_user_created_at
ON public.behavior_logs (
    user_id,
    created_at DESC
);


CREATE INDEX idx_behavior_logs_tour_created_at
ON public.behavior_logs (
    tour_id,
    created_at DESC
);


CREATE INDEX idx_behavior_logs_action_created_at
ON public.behavior_logs (
    action_type,
    created_at DESC
);


-- ------------------------------------------------------------
-- 4. Recommendation runs
--
-- One record represents one recommendation execution.
-- ------------------------------------------------------------

CREATE TABLE public.recommendation_runs (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id             INTEGER NOT NULL,

    algorithm_code      VARCHAR(80) NOT NULL,
    algorithm_version   VARCHAR(50) NOT NULL,

    context             JSONB NOT NULL DEFAULT '{}'::jsonb,

    generated_at        TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_recommendation_runs_users
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_recommendation_runs_algorithm_code
        CHECK (
            algorithm_code ~ '^[A-Z][A-Z0-9_]*$'
        ),

    CONSTRAINT ck_recommendation_runs_context_object
        CHECK (
            jsonb_typeof(context) = 'object'
        )
);


CREATE INDEX idx_recommendation_runs_user_generated_at
ON public.recommendation_runs (
    user_id,
    generated_at DESC
);


CREATE INDEX idx_recommendation_runs_algorithm
ON public.recommendation_runs (
    algorithm_code,
    algorithm_version
);


-- ------------------------------------------------------------
-- 5. Recommendation items
--
-- Individual ranked recommendations produced by a run.
-- ------------------------------------------------------------

CREATE TABLE public.recommendation_items (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    recommendation_run_id   BIGINT NOT NULL,
    tour_id                 INTEGER NOT NULL,

    rank_position           INTEGER NOT NULL,
    score                   NUMERIC(12,6),

    reason                  TEXT,

    CONSTRAINT fk_recommendation_items_runs
        FOREIGN KEY (recommendation_run_id)
        REFERENCES public.recommendation_runs(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_recommendation_items_tours
        FOREIGN KEY (tour_id)
        REFERENCES public.tours(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_recommendation_items_tour
        UNIQUE (
            recommendation_run_id,
            tour_id
        ),

    CONSTRAINT uq_recommendation_items_rank
        UNIQUE (
            recommendation_run_id,
            rank_position
        ),

    CONSTRAINT ck_recommendation_items_rank
        CHECK (
            rank_position > 0
        )
);


CREATE INDEX idx_recommendation_items_tour_id
ON public.recommendation_items (tour_id);


-- ------------------------------------------------------------
-- 6. Documentation
-- ------------------------------------------------------------

COMMENT ON TABLE public.user_preferences IS
'Customer preference profiles used by personalization and recommendation features.';

COMMENT ON TABLE public.favorites IS
'Customer-saved tours with one favorite relationship per user and tour.';

COMMENT ON TABLE public.behavior_logs IS
'Append-only interaction events used as recommendation signals and product analytics input.';

COMMENT ON TABLE public.recommendation_runs IS
'Recommendation execution history including algorithm identity and version.';

COMMENT ON TABLE public.recommendation_items IS
'Ranked tour recommendations generated by a recommendation run.';

COMMENT ON COLUMN public.recommendation_runs.algorithm_version IS
'Version identifier of the recommendation algorithm used for reproducibility.';

COMMENT ON COLUMN public.recommendation_items.score IS
'Optional model or ranking score. Score meaning depends on algorithm_code and algorithm_version.';