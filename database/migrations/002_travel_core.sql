    CONSTRAINT ck_tour_itineraries_day_number
        CHECK (
            day_number > 0
        )
);


CREATE INDEX idx_tour_itineraries_tour_id
ON public.tour_itineraries (tour_id);


CREATE TRIGGER trg_tour_itineraries_updated_at
BEFORE UPDATE ON public.tour_itineraries
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 7. Documentation
-- ------------------------------------------------------------

COMMENT ON TABLE public.destinations IS
'Canonical travel destinations managed by the STS platform. External-source provenance is added in a later migration.';

COMMENT ON TABLE public.tour_categories IS
'Platform-managed tour categories. Application logic should use category code when semantic identification is required.';

COMMENT ON TABLE public.tours IS
'Travel products owned by a company. Tour-level data does not store mutable departure price or seat availability.';

COMMENT ON COLUMN public.tours.company_id IS
'Travel company that owns this tour. Tenant-scoped backend queries must derive company identity from authenticated context.';

COMMENT ON TABLE public.tour_departures IS
'Concrete scheduled departures of a tour. Available slots are derived from capacity minus active booking guest counts.';

COMMENT ON COLUMN public.tour_departures.capacity IS
'Maximum number of guests accepted for this departure.';

COMMENT ON TABLE public.tour_images IS
'Tour media. A partial unique index ensures at most one primary image per tour.';

COMMENT ON TABLE public.tour_itineraries IS
'Day-by-day itinerary content belonging to a tour.';