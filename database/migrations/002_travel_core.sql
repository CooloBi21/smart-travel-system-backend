-- ------------------------------------------------------------
-- 1. Destinations
-- Platform-owned canonical travel destinations.
-- ------------------------------------------------------------

CREATE TABLE public.destinations (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    name            VARCHAR(180) NOT NULL,
    slug            VARCHAR(200) NOT NULL,

    description     TEXT,
    location_name   VARCHAR(180) NOT NULL,

    latitude        NUMERIC(9,6) NOT NULL,
    longitude       NUMERIC(9,6) NOT NULL,

    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_destinations_slug
        UNIQUE (slug),

    CONSTRAINT ck_destinations_slug_format
        CHECK (
            slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
        ),

    CONSTRAINT ck_destinations_latitude
        CHECK (
            latitude >= -90
            AND latitude <= 90
        ),

    CONSTRAINT ck_destinations_longitude
        CHECK (
            longitude >= -180
            AND longitude <= 180
        ),

    CONSTRAINT ck_destinations_status
        CHECK (
            status IN (
                'ACTIVE',
                'INACTIVE',
                'ARCHIVED'
            )
        )
);


CREATE INDEX idx_destinations_status
ON public.destinations (status);


CREATE INDEX idx_destinations_location_name
ON public.destinations (location_name);


CREATE TRIGGER trg_destinations_updated_at
BEFORE UPDATE ON public.destinations
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 2. Tour categories
-- ------------------------------------------------------------

CREATE TABLE public.tour_categories (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    code            VARCHAR(50) NOT NULL,
    name            VARCHAR(120) NOT NULL,
    description     TEXT,

    is_active       BOOLEAN NOT NULL DEFAULT TRUE,

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT uq_tour_categories_code
        UNIQUE (code),

    CONSTRAINT ck_tour_categories_code_format
        CHECK (
            code ~ '^[A-Z][A-Z0-9_]*$'
        )
);


CREATE UNIQUE INDEX uq_tour_categories_name_ci
ON public.tour_categories (LOWER(name));


CREATE INDEX idx_tour_categories_active
ON public.tour_categories (is_active);


CREATE TRIGGER trg_tour_categories_updated_at
BEFORE UPDATE ON public.tour_categories
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 3. Tours
--
-- Tour is the reusable travel product.
-- Pricing and capacity belong to tour_departures.
-- ------------------------------------------------------------

CREATE TABLE public.tours (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    company_id          INTEGER NOT NULL,
    destination_id      INTEGER NOT NULL,
    category_id         INTEGER NOT NULL,

    title               VARCHAR(255) NOT NULL,
    slug                VARCHAR(200) NOT NULL,

    description         TEXT,

    duration_days       INTEGER NOT NULL,
    travel_style        VARCHAR(30) NOT NULL,

    cancellation_policy TEXT,

    status              VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    published_at        TIMESTAMPTZ,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_tours_companies
        FOREIGN KEY (company_id)
        REFERENCES public.companies(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_tours_destinations
        FOREIGN KEY (destination_id)
        REFERENCES public.destinations(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_tours_categories
        FOREIGN KEY (category_id)
        REFERENCES public.tour_categories(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_tours_company_slug
        UNIQUE (company_id, slug),

    CONSTRAINT ck_tours_slug_format
        CHECK (
            slug ~ '^[a-z0-9]+(-[a-z0-9]+)*$'
        ),

    CONSTRAINT ck_tours_duration_days
        CHECK (
            duration_days > 0
        ),

    CONSTRAINT ck_tours_travel_style
        CHECK (
            travel_style IN (
                'BEACH',
                'CULTURE',
                'EXPLORE',
                'RELAX',
                'ADVENTURE'
            )
        ),

    CONSTRAINT ck_tours_status
        CHECK (
            status IN (
                'DRAFT',
                'PUBLISHED',
                'PAUSED',
                'ARCHIVED'
            )
        ),

    CONSTRAINT ck_tours_published_at
        CHECK (
            status <> 'PUBLISHED'
            OR published_at IS NOT NULL
        )
);


CREATE INDEX idx_tours_company_status
ON public.tours (
    company_id,
    status
);


CREATE INDEX idx_tours_destination_status
ON public.tours (
    destination_id,
    status
);


CREATE INDEX idx_tours_category_id
ON public.tours (category_id);


CREATE INDEX idx_tours_travel_style
ON public.tours (travel_style);


CREATE TRIGGER trg_tours_updated_at
BEFORE UPDATE ON public.tours
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 4. Tour departures
--
-- A departure represents one concrete scheduled trip.
-- Availability is derived from capacity and active bookings.
-- available_slots is intentionally NOT stored.
-- ------------------------------------------------------------

CREATE TABLE public.tour_departures (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    tour_id             INTEGER NOT NULL,

    departure_date      DATE NOT NULL,

    price_per_person    NUMERIC(14,2) NOT NULL,
    capacity            INTEGER NOT NULL,

    status              VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_tour_departures_tours
        FOREIGN KEY (tour_id)
        REFERENCES public.tours(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_tour_departures_tour_date
        UNIQUE (
            tour_id,
            departure_date
        ),

    CONSTRAINT ck_tour_departures_price
        CHECK (
            price_per_person >= 0
        ),

    CONSTRAINT ck_tour_departures_capacity
        CHECK (
            capacity > 0
        ),

    CONSTRAINT ck_tour_departures_status
        CHECK (
            status IN (
                'SCHEDULED',
                'CLOSED',
                'CANCELLED',
                'COMPLETED'
            )
        )
);


CREATE INDEX idx_tour_departures_tour_status_date
ON public.tour_departures (
    tour_id,
    status,
    departure_date
);


CREATE INDEX idx_tour_departures_status_date
ON public.tour_departures (
    status,
    departure_date
);


CREATE TRIGGER trg_tour_departures_updated_at
BEFORE UPDATE ON public.tour_departures
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 5. Tour images
-- ------------------------------------------------------------

CREATE TABLE public.tour_images (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    tour_id         INTEGER NOT NULL,

    image_url       TEXT NOT NULL,
    alt_text        VARCHAR(255),

    is_primary      BOOLEAN NOT NULL DEFAULT FALSE,
    sort_order      INTEGER NOT NULL DEFAULT 0,

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_tour_images_tours
        FOREIGN KEY (tour_id)
        REFERENCES public.tours(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_tour_images_sort_order
        CHECK (
            sort_order >= 0
        )
);


CREATE INDEX idx_tour_images_tour_id
ON public.tour_images (tour_id);


CREATE UNIQUE INDEX uq_tour_images_one_primary
ON public.tour_images (tour_id)
WHERE is_primary = TRUE;


CREATE TRIGGER trg_tour_images_updated_at
BEFORE UPDATE ON public.tour_images
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 6. Tour itineraries
