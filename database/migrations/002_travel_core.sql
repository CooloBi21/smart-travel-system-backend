    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_tour_itineraries_tours
        FOREIGN KEY (tour_id)
        REFERENCES public.tours(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_tour_itineraries_day
