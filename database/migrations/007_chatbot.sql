-- ------------------------------------------------------------
-- 1. Chat sessions
--
-- One row represents one chatbot conversation session.
-- user_id is nullable so the session model can support
-- anonymous conversations in the future.
-- ------------------------------------------------------------

CREATE TABLE public.chat_sessions (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id     INTEGER,

    started_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    ended_at    TIMESTAMPTZ,

    CONSTRAINT fk_chat_sessions_user
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON DELETE SET NULL,

    CONSTRAINT ck_chat_sessions_lifecycle
        CHECK (
            ended_at IS NULL
            OR ended_at >= started_at
        )
);


CREATE INDEX idx_chat_sessions_user_started
ON public.chat_sessions (
    user_id,
    started_at DESC
);


CREATE INDEX idx_chat_sessions_started
ON public.chat_sessions (
    started_at DESC
);


-- ------------------------------------------------------------
-- 2. Chat messages
--
-- Stores the conversation messages belonging to a session.
-- sender_type distinguishes customer messages from AI replies.
-- ------------------------------------------------------------

CREATE TABLE public.chat_messages (
    id              INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    session_id      INTEGER NOT NULL,

    sender_type     VARCHAR(20) NOT NULL,

    message_text    TEXT NOT NULL,

    intent_detected VARCHAR(50),

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_chat_messages_session
        FOREIGN KEY (session_id)
        REFERENCES public.chat_sessions(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_chat_messages_sender_type
        CHECK (
            sender_type IN (
                'CUSTOMER',
                'AI_ASSISTANT'
            )
        ),

    CONSTRAINT ck_chat_messages_text
        CHECK (
            BTRIM(message_text) <> ''
        ),

    CONSTRAINT ck_chat_messages_intent
        CHECK (
            intent_detected IS NULL
            OR BTRIM(intent_detected) <> ''
        )
);


CREATE INDEX idx_chat_messages_session_created
ON public.chat_messages (
    session_id,
    created_at ASC
);


CREATE INDEX idx_chat_messages_sender_created
ON public.chat_messages (
    sender_type,
    created_at DESC
);


-- ------------------------------------------------------------
-- 3. Documentation
-- ------------------------------------------------------------

COMMENT ON TABLE public.chat_sessions IS
'Chatbot conversation sessions. A session may optionally be associated with a registered user.';

COMMENT ON TABLE public.chat_messages IS
'Messages exchanged between customers and the STS chatbot within a chat session.';

COMMENT ON COLUMN public.chat_sessions.user_id IS
'Registered user associated with the conversation. NULL allows future anonymous chatbot sessions.';

COMMENT ON COLUMN public.chat_messages.sender_type IS
'Message sender type: CUSTOMER or AI_ASSISTANT.';

COMMENT ON COLUMN public.chat_messages.message_text IS
'Original chatbot conversation message content.';

COMMENT ON COLUMN public.chat_messages.intent_detected IS
'Optional chatbot intent detected from the customer message.';

COMMENT ON COLUMN public.chat_messages.created_at IS
'Time when the message was persisted.';
