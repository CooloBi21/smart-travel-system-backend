-- ------------------------------------------------------------
-- 1. Bookings
--
-- One booking represents one customer booking one concrete
-- tour departure.
--
-- unit_price is a historical price snapshot.
-- total_amount is intentionally NOT stored because it is
-- derived from guest_count * unit_price.
-- ------------------------------------------------------------

CREATE TABLE public.bookings (
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id             INTEGER NOT NULL,
    tour_departure_id   INTEGER NOT NULL,

    guest_count         INTEGER NOT NULL,
    unit_price          NUMERIC(14,2) NOT NULL,

    contact_name        VARCHAR(150) NOT NULL,
    contact_email       VARCHAR(255) NOT NULL,
    contact_phone       VARCHAR(30),

    special_request     TEXT,

    status              VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    confirmed_at        TIMESTAMPTZ,
    cancelled_at        TIMESTAMPTZ,
    completed_at        TIMESTAMPTZ,

    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_bookings_users
        FOREIGN KEY (user_id)
        REFERENCES public.users(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_bookings_departures
        FOREIGN KEY (tour_departure_id)
        REFERENCES public.tour_departures(id)
        ON DELETE RESTRICT,

    CONSTRAINT ck_bookings_guest_count
        CHECK (
            guest_count > 0
        ),

    CONSTRAINT ck_bookings_unit_price
        CHECK (
            unit_price >= 0
        ),

    CONSTRAINT ck_bookings_contact_name
        CHECK (
            BTRIM(contact_name) <> ''
        ),

    CONSTRAINT ck_bookings_contact_email
        CHECK (
            BTRIM(contact_email) <> ''
        ),

    CONSTRAINT ck_bookings_status
        CHECK (
            status IN (
                'PENDING',
                'CONFIRMED',
                'CANCELLED',
                'COMPLETED'
            )
        ),

    CONSTRAINT ck_bookings_lifecycle_timestamps
        CHECK (
            (
                status = 'PENDING'
                AND confirmed_at IS NULL
                AND cancelled_at IS NULL
                AND completed_at IS NULL
            )
            OR
            (
                status = 'CONFIRMED'
                AND confirmed_at IS NOT NULL
                AND cancelled_at IS NULL
                AND completed_at IS NULL
            )
            OR
            (
                status = 'CANCELLED'
                AND cancelled_at IS NOT NULL
                AND completed_at IS NULL
            )
            OR
            (
                status = 'COMPLETED'
                AND confirmed_at IS NOT NULL
                AND completed_at IS NOT NULL
                AND cancelled_at IS NULL
                AND completed_at >= confirmed_at
            )
        )
);


CREATE INDEX idx_bookings_user_created_at
ON public.bookings (
    user_id,
    created_at DESC
);


CREATE INDEX idx_bookings_departure_status
ON public.bookings (
    tour_departure_id,
    status
);


CREATE INDEX idx_bookings_status_created_at
ON public.bookings (
    status,
    created_at
);


CREATE TRIGGER trg_bookings_updated_at
BEFORE UPDATE ON public.bookings
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 2. Derived departure availability
--
-- PENDING and CONFIRMED bookings reserve capacity.
-- Availability is calculated instead of stored.
-- ------------------------------------------------------------

CREATE VIEW public.tour_departure_availability AS

SELECT
    td.id AS tour_departure_id,
    td.tour_id,
    td.departure_date,
    td.capacity,

    COALESCE(
        SUM(b.guest_count)
        FILTER (
            WHERE b.status IN (
                'PENDING',
                'CONFIRMED'
            )
        ),
        0
    )::INTEGER AS reserved_slots,

    (
        td.capacity
        -
        COALESCE(
            SUM(b.guest_count)
            FILTER (
                WHERE b.status IN (
                    'PENDING',
                    'CONFIRMED'
                )
            ),
            0
        )
    )::INTEGER AS available_slots

FROM public.tour_departures td

LEFT JOIN public.bookings b
    ON b.tour_departure_id = td.id

GROUP BY
    td.id,
    td.tour_id,
    td.departure_date,
    td.capacity;


-- ------------------------------------------------------------
-- 3. Reviews
--
-- A completed booking may have at most one review.
-- User and tour are derived through the booking relationship,
-- so reviews do not duplicate user_id or tour_id.
-- ------------------------------------------------------------

CREATE TABLE public.reviews (
    id                      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    booking_id              INTEGER NOT NULL,

    rating                  INTEGER NOT NULL,
    comment                 TEXT NOT NULL,

    sentiment_label         VARCHAR(20),
    sentiment_confidence    NUMERIC(6,5),
    sentiment_model_version VARCHAR(100),
    sentiment_analyzed_at   TIMESTAMPTZ,

    created_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT fk_reviews_bookings
        FOREIGN KEY (booking_id)
        REFERENCES public.bookings(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_reviews_booking
        UNIQUE (booking_id),

    CONSTRAINT ck_reviews_rating
        CHECK (
            rating BETWEEN 1 AND 5
        ),

    CONSTRAINT ck_reviews_comment
        CHECK (
            BTRIM(comment) <> ''
        ),

    CONSTRAINT ck_reviews_sentiment_label
        CHECK (
            sentiment_label IS NULL
            OR sentiment_label IN (
                'POSITIVE',
                'NEUTRAL',
                'NEGATIVE'
            )
        ),

    CONSTRAINT ck_reviews_sentiment_confidence
        CHECK (
            sentiment_confidence IS NULL
            OR (
                sentiment_confidence >= 0
                AND sentiment_confidence <= 1
            )
        )
);


CREATE INDEX idx_reviews_created_at
ON public.reviews (created_at DESC);


CREATE TRIGGER trg_reviews_updated_at
BEFORE UPDATE ON public.reviews
FOR EACH ROW
EXECUTE FUNCTION public.update_timestamp();


-- ------------------------------------------------------------
-- 4. Documentation
