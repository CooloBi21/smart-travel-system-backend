COMMENT ON TABLE public.bookings IS
'Customer bookings for concrete tour departures. Seat availability is derived from active booking guest counts.';

COMMENT ON COLUMN public.bookings.unit_price IS
'Immutable price-per-person snapshot captured when the booking is created.';

COMMENT ON COLUMN public.bookings.status IS
'Booking lifecycle: PENDING, CONFIRMED, CANCELLED, COMPLETED.';

COMMENT ON VIEW public.tour_departure_availability IS
'Derived availability for each departure. PENDING and CONFIRMED bookings reserve capacity.';

COMMENT ON TABLE public.reviews IS
'Customer reviews tied one-to-one to bookings. Review eligibility for completed bookings is enforced by the application service layer.';

COMMENT ON COLUMN public.reviews.sentiment_confidence IS
'AI sentiment confidence score in the inclusive range 0 to 1.';